package org.openrewrite.recipe.quarkus.internal;

import org.jspecify.annotations.NullMarked;
import org.jspecify.annotations.Nullable;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.BasicFileAttributes;
import java.util.*;
import java.util.function.BiPredicate;
import java.util.regex.MatchResult;
import java.util.regex.Pattern;

import static java.util.Comparator.comparing;

@NullMarked
public class AggregateQuarkusUpdates {

    public static void main(String[] args) throws Exception {
        if (args.length < 2) {
            IO.println("Usage: java AggregateQuarkusUpdates <path to quarkus-updates recipes> <path to consolidated recipes>");
        }

        Path quarkusRecipesDirectory = Path.of(args[0]);
        Path consolidatedRecipe = Path.of(args[1]);

        System.out.printf("Starting aggregation of Quarkus update recipes from %s to %s%n", quarkusRecipesDirectory.toAbsolutePath(), consolidatedRecipe.toAbsolutePath());

        if (!quarkusRecipesDirectory.toFile().exists()) {
            throw new IllegalStateException("quarkusio/quarkus-updates.git is not available under 'quarkus-updates', please clone here temporarily");
        }

        System.out.printf("Reading recipes from %s%n", quarkusRecipesDirectory.toAbsolutePath());
        SortedMap<Version, VersionRecipes> sortedByVersion = recipesDefinedInQuarkusRepo(quarkusRecipesDirectory);

        System.out.printf(
          "Found %s different versions and %s recipes in total%n",
          sortedByVersion.size(),
          sortedByVersion.values().stream().mapToInt(VersionRecipes::size).sum());

        StringBuilder recipeYml = new StringBuilder();
        recipeYml.append("# This file is auto-generated by running `./gradlew generateQuarkusAggregation`\n");

        Version prior = null;
        for (Map.Entry<Version, VersionRecipes> entry : sortedByVersion.entrySet()) {
            Version current = entry.getKey();
            VersionRecipes recipes = entry.getValue();
            if (recipes.size() == 0) {
                continue;
            }

            System.out.printf("\t%s has %d recipes%n", current, recipes.size());
            recipeYml.append(createRecipe(current, prior, recipes));
            prior = current;
        }

        try {
            Files.writeString(consolidatedRecipe, recipeYml);
            System.out.printf("Wrote aggregating recipes to %s", consolidatedRecipe.toAbsolutePath());
        } catch (IOException e) {
            System.err.printf("Failed to write to %s due to %s", consolidatedRecipe.toAbsolutePath(), e.getMessage());
        }

    }

    private static final BiPredicate<Path, BasicFileAttributes> yamlFileFilter = (p, a) -> p.getFileName().toString().endsWith(".yml") || p.getFileName().toString().endsWith(".yaml");

    /// Read the recipes from the `quarkus-updates` directory, which holds the core recipes under `core/` and the recipes
    /// of an extension under `<groupId>/<artifactId>/`, each file named for the version it updates to.
    static SortedMap<Version, VersionRecipes> recipesDefinedInQuarkusRepo(Path quarkusRecipesDirectory) throws IOException {
        // Sorted, such that the recipes of `4.0.alpha1.yaml` come before those of `4.0.0.beta2.yaml`, both folded into 4.0.0
        List<Path> recipesFiles = Files.find(quarkusRecipesDirectory, 3, yamlFileFilter)
          .sorted(comparing((Path p) -> p.getParent().toString())
            .thenComparing(p -> Version.parse(p.getFileName().toString()))
            .thenComparing(AggregateQuarkusUpdates::qualifierRank)
            .thenComparing(p -> p.getFileName().toString()))
          .toList();
        SortedMap<Version, VersionRecipes> sortedByVersion = new TreeMap<>();
        for (Path recipe : recipesFiles) {
            var version = Version.parse(recipe.getFileName().toString());
            var recipeNames = extractRecipeNames(recipe);
            var extension = Extension.fromDirectory(quarkusRecipesDirectory.relativize(recipe.getParent()));
            sortedByVersion.computeIfAbsent(version, v -> new VersionRecipes()).add(extension, recipeNames);
        }
        return sortedByVersion;
    }

    private static int qualifierRank(Path recipeFile) {
        String name = recipeFile.getFileName().toString().toLowerCase();
        if (name.contains("alpha")) {
            return 0;
        }
        if (name.contains("beta")) {
            return 1;
        }
        if (name.contains("cr")) {
            return 2;
        }
        return 3;
    }

    /// Normalize recipe name for a given version, the entry point that upgrades to that version
    static String recipeNameFor(Version version) {
        return "org.openrewrite.quarkus.MigrateToQuarkus_v%s_%s_%s".formatted(version.major, version.minor, version.patch);
    }

    /// Normalize recipe name for the update recipes of a given version and those before it, without the platform upgrade
    static String updatesRecipeNameFor(Version version) {
        return "org.openrewrite.quarkus.QuarkusUpdates_v%s_%s_%s".formatted(version.major, version.minor, version.patch);
    }

    /// Normalize recipe name for the recipes of an extension at a given version
    static String updatesRecipeNameFor(Version version, Extension extension) {
        return updatesRecipeNameFor(version) + "_" + extension.artifactId().replaceAll("\\W", "_");
    }

    /// Create the recipes for a specific version, chaining in the prior version's update recipes if there is one.
    /// Like `quarkus update`, the entry point first upgrades the Quarkus platform, once, and then runs the update recipes
    /// of every version up to this one. These apply to every file of a repository that uses Quarkus, such as its CI
    /// workflows and Dockerfiles, and the recipes of an extension only where that extension is used.
    static String createRecipe(Version version, @Nullable Version priorVersion, VersionRecipes recipes) {
        List<String> recipeList = new ArrayList<>();
        if (priorVersion != null) {
            recipeList.add(updatesRecipeNameFor(priorVersion));
        }
        recipeList.addAll(recipes.core());
        recipes.extensions().keySet().forEach(extension -> recipeList.add(updatesRecipeNameFor(version, extension)));

        StringBuilder yaml = new StringBuilder(
          // language=YAML
          """
            ---
            type: specs.openrewrite.org/v1beta/recipe
            name: %1$s
            displayName: Quarkus Updates Aggregate %2$s
            description: Quarkus update recipes to upgrade your application to %2$s.
            preconditions:
              - org.openrewrite.java.dependencies.search.RepositoryHasDependency:
                  groupIdPattern: io.quarkus
                  artifactIdPattern: quarkus-core
                  version: (,%2$s)
            recipeList:
              - org.openrewrite.quarkus.UpgradeQuarkusVersion:
                  newVersion: %3$s
              - %4$s

            ---
            type: specs.openrewrite.org/v1beta/recipe
            name: %4$s
            displayName: Quarkus update recipes up to %2$s
            description: The Quarkus update recipes of %2$s and the versions before it, without upgrading the Quarkus platform itself.
            preconditions:
              - org.openrewrite.java.dependencies.search.RepositoryHasDependency:
                  groupIdPattern: io.quarkus
                  artifactIdPattern: quarkus-core
                  version: (,%2$s)
            recipeList:
              - %5$s

            """.formatted(
            recipeNameFor(version),
            version,
            version.platformSelector(),
            updatesRecipeNameFor(version),
            String.join("\n  - ", recipeList)));

        recipes.extensions().forEach((extension, extensionRecipes) -> yaml.append(
          // language=YAML
          """
            ---
            type: specs.openrewrite.org/v1beta/recipe
            name: %1$s
            displayName: Quarkus update recipes of %2$s for `%4$s`
            description: Update recipes for `%3$s:%4$s` %2$s, applied only where `%3$s:%4$s*` is used, as `quarkus update` does.
            preconditions:
              - org.openrewrite.java.dependencies.search.RepositoryHasDependency:
                  groupIdPattern: %3$s
                  artifactIdPattern: %4$s*
                  version: (,%2$s)
            recipeList:
              - %5$s

            """.formatted(
            updatesRecipeNameFor(version, extension),
            version,
            extension.groupId(),
            extension.artifactId(),
            String.join("\n  - ", extensionRecipes))));
        return yaml.toString();
    }

    /// Parse the defined recipe names from a given file using `type: specs.openrewrite.org/v1beta/recipe\nname: ([\.\w]*)``
    static List<String> extractRecipeNames(Path file) {
        Pattern compile = Pattern.compile("type: specs.openrewrite.org/v1beta/recipe\\nname: ([.\\w]*)");
        try {
            List<String> recipeNames = new ArrayList<>();
            for (MatchResult recipeNamesResults : compile.matcher(Files.readString(file)).results().toList()) {
                String recipeName = recipeNamesResults.group(1);
                if ("io.quarkus.updates.minio.minio38.UpdateProperties".equals(recipeName)) {
                    continue;
                }
                recipeNames.add(recipeName);
            }
            return List.copyOf(recipeNames);
        } catch (IOException e) {
            throw new RuntimeException(e);
        }
    }

    /// The extension whose recipes live in `<groupId>/<artifactId>/`, which `quarkus update` applies to any dependency on
    /// `<groupId>:<artifactId>*`, or `null` for the core recipes.
    record Extension(String groupId, String artifactId) implements Comparable<Extension> {
        static @Nullable Extension fromDirectory(Path relativeDirectory) {
            if (relativeDirectory.getNameCount() != 2) {
                return null;
            }
            return new Extension(relativeDirectory.getName(0).toString(), relativeDirectory.getName(1).toString());
        }

        @Override
        public int compareTo(Extension other) {
            return comparing(Extension::groupId).thenComparing(Extension::artifactId).compare(this, other);
        }
    }

    /// The core recipes and the recipes of each extension that update to one version.
    record VersionRecipes(List<String> core, SortedMap<Extension, List<String>> extensions) {
        VersionRecipes() {
            this(new ArrayList<>(), new TreeMap<>());
        }

        void add(@Nullable Extension extension, List<String> recipeNames) {
            if (extension == null) {
                core.addAll(recipeNames);
            } else if (!recipeNames.isEmpty()) {
                extensions.computeIfAbsent(extension, e -> new ArrayList<>()).addAll(recipeNames);
            }
        }

        int size() {
            return core.size() + extensions.values().stream().mapToInt(List::size).sum();
        }
    }

    record Version(int major, int minor, Integer patch) implements Comparable<Version> {
        /**
         * The recipe name of a Quarkus update recipe contains the target version.
         */
        public static Version parse(String version) {
            if ("3alpha.yaml".equals(version)) {
                // Special case for the initial Quarkus 3 alpha recipe
                return new Version(3, 0, 0);
            }

            String[] parts = version.split("\\.");
            int major = Integer.parseInt(parts[0]);
            int minor = parts.length > 1 ? Integer.parseInt(parts[1]) : 0;

            // handle cases like 2.13.yaml and fold to 2.13.0
            if (parts.length < 3 ||
              Objects.equals(parts[2], "yaml") // fold 2.13.alphaX.yaml into 2.13
              ||
              // fold 2.13.alphaX.yaml into 2.13
              parts[2].startsWith("alpha")) {
                return new Version(major, minor, 0);
            }

            // handle cases like 2.13.X.yaml
            return new Version(major, minor, Integer.parseInt(parts[2]));
        }

        /// The newest release of this minor version, such as `3.20.x` for both 3.20.0 and 3.20.1
        String platformSelector() {
            return "%s.%s.x".formatted(major, minor);
        }

        private static final Comparator<Version> versionComparator = comparing(Version::major).thenComparing(Version::minor).thenComparing(Version::patch);

        @Override
        public int compareTo(Version other) {
            return versionComparator.compare(this, other);
        }

        @Override
        public String toString() {
            return "%s.%s.%s".formatted(major, minor, patch);
        }
    }
}
